const pad = (n: number) => String(n).padStart(2, '0');
const jong = (word: string) => {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  return code >= 0 && code < 11172 ? code % 28 : 0;
};
/** 스터디로, 미루기 아카이빙으로: 로 after a vowel or ㄹ, 으로 after other final consonants. */
export const withRo = (word: string) => word + (jong(word) === 0 || jong(word) === 8 ? '로' : '으로');
/** 이 or 가, for "<domain>이 맞아요". */
export const withIGa = (word: string) => word + (jong(word) === 0 ? '가' : '이');
const monthDay = (d: Date) => `${d.getMonth() + 1}월 ${d.getDate()}일`;
const clock = (d: Date) => `${d.getHours() < 12 ? '오전' : '오후'} ${d.getHours() % 12 === 0 ? 12 : d.getHours() % 12}:${pad(d.getMinutes())}`;

